def main() -> int:
    parser = argparse.ArgumentParser(description="Dataset-aware GOOD sweep for DSS hybrid variants")
    parser.add_argument("--stage", default=DEFAULT_STAGE, choices=sorted(DEFAULT_TAG_PREFIX.keys()))
    parser.add_argument("--targets", nargs="*", default=None, help="GOOD targets to include in the sweep.")
    parser.add_argument("--target", default=None, help="Single GOOD target alias for Slurm array use.")
    parser.add_argument("--runs", type=int, default=3, help="Runs per sweep job.")
    parser.add_argument("--epochs", type=int, default=150, help="Default epochs per sweep job.")
    parser.add_argument("--patience", type=int, default=50, help="Default patience per sweep job.")
    parser.add_argument("--device", type=int, default=0, help="CUDA device index for execution.")
    parser.add_argument("--python-bin", default=None, help="Python executable to use for launched jobs.")
    parser.add_argument("--tag-prefix", default=None, help="Prefix for result tags.")
    parser.add_argument("--job-index", type=int, default=None, help="Execute the indexed job.")
    parser.add_argument("--count", action="store_true", help="Print the number of jobs and exit.")
    parser.add_argument("--list", action="store_true", help="List the planned jobs and exit.")
    parser.add_argument("--show-jobs", type=int, default=None, help="Show only the first N planned jobs.")
    parser.add_argument("--skip-existing", action="store_true", help="Skip jobs whose summary.csv already exists.")
    parser.add_argument("--generate", action="store_true", help="Pass --generate through to the GOOD runner.")
    parser.add_argument("--cpu", action="store_true", help="Force CPU execution for debugging.")
    args = parser.parse_args()

    if args.target is not None:
        target_keys = target_keys_from_args(args.stage, [args.target])
    else:
        target_keys = target_keys_from_args(args.stage, args.targets)

    tag_prefix = args.tag_prefix or DEFAULT_TAG_PREFIX[args.stage]
    jobs = build_jobs(args.stage, target_keys, runs=args.runs, epochs=args.epochs, patience=args.patience, tag_prefix=tag_prefix)

    if args.count:
        print(len(jobs))
        return 0
    if args.list:
        print_jobs(args.stage, jobs, limit=args.show_jobs)
        return 0
    if args.job_index is None:
        print_jobs(args.stage, jobs, limit=args.show_jobs)
        print("\nUse --job-index to execute a specific GOOD sweep job.")
        return 0
    if args.job_index < 0 or args.job_index >= len(jobs):
        raise SystemExit(f"Job index {args.job_index} is out of range for {len(jobs)} jobs.")

    return run_job(jobs[args.job_index], args)


if __name__ == "__main__":
    raise SystemExit(main())
