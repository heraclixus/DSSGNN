def merge_parts(parts):
    merged = {}
    for part in parts:
        merged.update(part)
    return merged


def target_keys_from_args(stage: str, target_values: list[str] | None) -> list[str]:
    stage_specs = TARGET_SPECS_BY_STAGE[stage]
    if not target_values:
        return list(stage_specs.keys())
    bad = [target for target in target_values if target not in stage_specs]
    if bad:
        raise SystemExit(f"Unsupported GOOD {stage} targets: {', '.join(bad)}")
    return target_values


def build_jobs(stage: str, target_keys: list[str], runs: int, epochs: int, patience: int, tag_prefix: str):
    stage_specs = TARGET_SPECS_BY_STAGE[stage]
    jobs = []
    for target in target_keys:
        spec = stage_specs[target]
        axis_values = [values for _name, values in spec["axes"]]
        for local_idx, combo in enumerate(itertools.product(*axis_values)):
            merged = merge_parts(combo)
            note_parts = [spec["note"]]
            for part in combo:
                if "note" in part:
                    note_parts.append(part["note"])
            record = {
                "stage": stage,
                "target": target,
                "dataset": spec["dataset"],
                "slug": spec["slug"],
                "model": merged["model"],
                "runs": runs,
                "epochs": merged.get("epochs", epochs),
                "patience": merged.get("patience", patience),
                "tag": f"{tag_prefix}_{target}_g{local_idx:02d}",
                "note": " ".join(dict.fromkeys(note_parts)),
            }
            if "artifact_test_acc_threshold" in spec:
                record["artifact_test_acc_threshold"] = spec["artifact_test_acc_threshold"]
            for key, value in merged.items():
                if key not in {"note"}:
                    record[key] = value
            jobs.append(record)
    return jobs


