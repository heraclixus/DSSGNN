def run_job(job: dict, args) -> int:
    out_dir = REPO_ROOT / "results_local" / "good_density" / f"{job['slug']}-{job['tag']}"
    summary_path = out_dir / "summary.csv"
    if args.skip_existing and summary_path.exists():
        print(f"Skipping existing GOOD sweep bundle: {summary_path}")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = command_for_job(job, args)
    print("GOOD sweep job:")
    print(json.dumps(job, indent=2))
    print("Command:")
    print(" ".join(cmd))
    subprocess.run(cmd, cwd=REPO_ROOT, check=True)
    (out_dir / "sweep_job.json").write_text(json.dumps(job, indent=2))
    print(f"Wrote sweep metadata to {out_dir / 'sweep_job.json'}")
    return 0


